/**
 * The ESLint majors an adopting project may be on. Every package in
 * {@link REQUIRED_DEPS} must declare a peer range admitting all of them:
 * `npm install` resolves the whole list or none of it, so one package that
 * caps below the project's ESLint fails the entire install — and `init` is
 * left with a half-applied plan (field issue #37).
 */
export const SUPPORTED_ESLINT_MAJORS = [9, 10];

export const REQUIRED_DEPS = [
  'eslint',
  '@kekkai/blueprint',
  '@eslint-community/eslint-plugin-eslint-comments',
  // Carriers for the shape family and importBlock. The library depends on
  // neither plugin — the generated config injects them, so the packages are
  // the project's deps, not blueprint's.
  //
  // importBlock rides `eslint-plugin-import-x`, and the two walls it walks
  // around are why. `eslint-plugin-import` caps its eslint peer at 9 (field
  // issue #37). `eslint-plugin-import-x` clears that, but peers on
  // `@typescript-eslint/utils@^8.56` for its resolvers: an optional peer is
  // still version-checked when the package is PRESENT, and a peer cannot be
  // satisfied by a nested copy — so any repo pinned below that failed the
  // whole install (field issue #41). import-x is those same rules ported
  // without the resolvers, which is exactly what pulled that peer: zero
  // dependencies, and `eslint` as its only peer.
  '@stylistic/eslint-plugin',
  'eslint-plugin-import-x',
];

/** Carriers added only when the detected stack needs their parser. */
export const STACK_DEPS = {
  vue: 'vue-eslint-parser',
  typescript: 'typescript-eslint',
} as const;

/**
 * Non-`eslint` peers a carrier is allowed to declare, by package. A peer on
 * something the ADOPTER owns is a version constraint blueprint imposes on
 * their repo from the outside — npm enforces it whenever the package is
 * present, and no nested copy can satisfy it, so the install fails as a whole
 * (field issue #41). `typescript-eslint` ↔ `typescript` is inherent and wide;
 * anything new belongs in a review, not in someone's adoption.
 */
export const ALLOWED_CARRIER_PEERS: Record<string, string[]> = {
  'typescript-eslint': ['typescript'],
  // Taken deliberately, on the ESLint 10 baseline. Both are what `import-x`
  // carries that `import-lite` structurally could not: the resolver stack,
  // and with it the whole-graph rules (`no-cycle` above all) a resolver-free
  // plugin can never express.
  //
  // The #41 population is not empty, it is narrower: the constraint only
  // bites a tree that already holds `@typescript-eslint/utils` BELOW ^8.56,
  // and no honest resolution reaches ESLint 10 while doing so — older
  // typescript-eslint refuses ESLint 10 as its own peer. What is left is
  // repos already installing with `--legacy-peer-deps` / `--force`, whose
  // installs do not abort on peer conflicts in the first place.
  //
  // That reasoning is an argument, not evidence. The evidence is the
  // conformance stack fixtures — if one of them fails to install, this entry
  // is wrong and the carrier decision reopens.
  'eslint-plugin-import-x': ['@typescript-eslint/utils', 'eslint-import-resolver-node'],
};

function readJson(file: string): Record<string, unknown> | null {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8'));
  } catch {
    // Undecidable: an empty catch returns `undefined`, and every caller reads both as
    // "no readable JSON". Making the difference visible would mean a caller that
    // cares which flavour of absent it got, which is worse code than this note.
    return null;
  }
}

/**
 * The vite config's text, when there is one and it can be read.
 *
 * One function rather than `viteFile !== undefined && viteText !== null` at the
 * point of use. That compound asked the same question twice — the text is read FROM
 * the file, so a non-null text already implies a file — but TypeScript cannot see
 * the implication, so the redundant half had to stay for the narrowing and could
 * never be wrong. Written as a sequence, each step decides something: no file, or a
 * file nothing could read.
 */
function readViteConfig(
  root: string,
  file: string | undefined,
): { file: string; text: string } | undefined {
  if (file === undefined) return undefined;

  const text = readText(path.join(root, file));

  return text === null ? undefined : { file, text };
}

function readText(file: string): string | null {
  try {
    return fs.readFileSync(file, 'utf-8');
  } catch {
    return null;
  }
}

/** Read a set of project-relative files; each value is the content, or null if absent. */
export function readTexts(root: string, paths: string[]): Record<string, string | null> {
  return Object.fromEntries(paths.map((file) => [file, readText(path.join(root, file))]));
}

function detectFramework(deps: Record<string, unknown>): Framework | null {
  const hasVue = 'vue' in deps;
  const hasReact = 'react' in deps;

  if (hasVue === hasReact) return null; // both or neither → ambiguous

  return hasVue ? 'vue' : 'react';
}

/**
 * Walk from `root` upward until a package-manager marker is found. In a
 * workspace (pnpm / turbo monorepo) the lockfile lives at the workspace
 * root, not in the package being initialized — looking only at the cwd
 * would misdetect npm and generate the wrong install commands.
 */
function detectPackageManager(root: string): PackageManager {
  let dir = path.resolve(root);

  for (;;) {
    if (
      fs.existsSync(path.join(dir, 'pnpm-lock.yaml'))
      || fs.existsSync(path.join(dir, 'pnpm-workspace.yaml'))
    ) {
      return 'pnpm';
    }

    if (fs.existsSync(path.join(dir, 'yarn.lock'))) return 'yarn';
    if (fs.existsSync(path.join(dir, 'package-lock.json'))) return 'npm';

    const parent = path.dirname(dir);

    if (parent === dir) return 'npm';

    dir = parent;
  }
}

/**
 * Detect the Next.js route tree: which router (`app` / `pages` / both, for a
 * migration) and whether it sits under `src/`. Drives the Next preset shape
 * so a fresh `create-next-app` adopts in one command.
 */
function detectNext(
  root: string,
  hasNext: boolean,
): { nextRouter: 'app' | 'pages' | 'both' | null; nextSrcDir: boolean } {
  if (!hasNext) return { nextRouter: null, nextSrcDir: false };

  const has = (rel: string) => fs.existsSync(path.join(root, rel));
  const app = has('src/app') || has('app');
  const pages = has('src/pages') || has('pages');

  return {
    nextRouter: app && pages ? 'both' : app ? 'app' : pages ? 'pages' : null,
    nextSrcDir: has('src/app') || has('src/pages'),
  };
}

function listSrcDirs(root: string): string[] {
  try {
    return fs
      .readdirSync(path.join(root, 'src'), { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name);
  } catch {
    return [];
  }
}

/** Read the target project into a {@link ProjectState}. */
export function detect(root: string): ProjectState {
  const pkg = readJson(path.join(root, 'package.json')) ?? {};

  const deps = {
    ...((pkg.dependencies as Record<string, unknown>) ?? {}),
    ...((pkg.devDependencies as Record<string, unknown>) ?? {}),
  };

  const framework = detectFramework(deps);
  const hasTypescript = 'typescript' in deps;
  const hasNext = 'next' in deps;
  const hasNuxt = 'nuxt' in deps;
  const { nextRouter, nextSrcDir } = detectNext(root, hasNext);

  // The generated eslint config wires parsers for the detected stack — the
  // packages backing them join the install set.
  const required = [
    ...REQUIRED_DEPS,
    ...(framework === 'vue' ? [STACK_DEPS.vue] : []),
    ...(hasTypescript ? [STACK_DEPS.typescript] : []),
  ];

  const eslintFile = ESLINT_FILES.find((file) => fs.existsSync(path.join(root, file)));
  const eslintText = eslintFile === undefined ? null : readText(path.join(root, eslintFile));

  const ownedEslintConfig = eslintText?.startsWith(GENERATED_ESLINT_BANNER)
    ? eslintFile
    : undefined;

  // A hand-maintained config that already imports the package has been wired
  // by its owner — emitting a reference next to it would be nagging.
  const wiredEslintConfig
    = ownedEslintConfig === undefined && (eslintText?.includes('@kekkai/blueprint') ?? false);

  // A legacy `.eslintrc*` is NOT a flat config — writing a fresh
  // `eslint.config.mjs` next to it produces two configs / two ledgers. Detect
  // it so the merge instruction routes to the flat-config migration instead.
  const legacyEslintConfig = eslintFile === undefined
    ? LEGACY_ESLINT_FILES.find((file) => fs.existsSync(path.join(root, file)))
    : undefined;

  // The existing config's shape, so the merge instruction can be specific
  // rather than a generic snippet the user must adapt.
  const eslintConfigShape = legacyEslintConfig
    ? 'legacy'
    : eslintText?.includes('tseslint.config(')
      ? 'tseslint'
      : eslintFile !== undefined
        ? 'flat-array'
        : undefined;

  const viteFile = VITE_FILES.find((file) => fs.existsSync(path.join(root, file)));
  const viteConfig = readViteConfig(root, viteFile);

  return {
    root,
    framework,
    packageManager: detectPackageManager(root),
    projectName: typeof pkg.name === 'string' ? pkg.name : undefined,
    hasConfig: fs.existsSync(path.join(root, CONFIG_FILE)),
    hasEslintConfig: eslintFile !== undefined,
    eslintConfigFile: eslintFile,
    hasNext,
    hasNuxt,
    nextRouter,
    nextSrcDir,
    ownedEslintConfig,
    wiredEslintConfig,
    legacyEslintConfig,
    eslintConfigShape,
    viteConfig,
    // Separate on purpose: `hasViteConfig` is "a vite config is there", and an
    // unreadable one is still there. `viteConfig` is "and this is what it says".
    hasViteConfig: viteFile !== undefined,
    hasTypescript,
    tsconfigs: readTexts(root, TSCONFIG_FILES),
    existingSrcDirs: listSrcDirs(root),
    missingDeps: required.filter((dep) => !(dep in deps)),
  };
}

/**
 * Copy a string literal verbatim (honoring escapes) from `text[i]` into
 * `out`, returning the index after the closing quote. Both JSONC passes
 * need this: a tsconfig's own data contains `/*` (every `"@/*"` paths key),
 * so nothing may be stripped inside a string.
 */
/**
 * A literal that closed, or the offset the scan gave up at — never both.
 *
 * Four fields where two are meaningless on failure is what made the bounds above
 * unanswerable: on an unterminated literal the caller throws `copied` away, so
 * whether the copy ran one character too far changed nothing anyone could see. Two
 * shapes, and each field exists only where it means something.
 */
interface ClosedString {
  closed: true;
  copied: string;
  next: number;
}

type CopiedString = ClosedString | { closed: false; stoppedAt: number };

function copyString(text: string, i: number): CopiedString {
  let copied = text[i];

  i++;

  while (i < text.length && text[i] !== '"') {
    copied += text[i];

    if (text[i] === '\\' && i + 1 < text.length) {
      copied += text[i + 1];
      i++;
    }

    i++;
  }

  // Ran out of text before the closing quote: report where it came to rest, which
  // is what makes every bound above answerable — a scan one character too far
  // changes the number a reader is shown.
  if (i >= text.length) return { closed: false, stoppedAt: i };

  return { closed: true, copied: copied + text[i], next: i + 1 };
}

/**
 * Why a JSONC document could not be read, and the character offset the scan gave
 * up at. Reported rather than folded into one null: "I cannot read your tsconfig"
 * is not something an adopter can act on — and a failure with no position leaves
 * every bound in the scanner unanswerable, since running one character too far
 * produced the same bare null.
 */
export interface JsoncFailure {
  reason: 'unterminated-string' | 'unclosed-comment' | 'not-json';
  /**
   * Character offset the scan came to rest at. Absent — not zero — for
   * `not-json`: offset 0 is a legitimate position (a file whose first character
   * is already wrong), so a sentinel there would read as one, and the caller
   * could not tell "the reader has no position for you" from "look at the start
   * of the file".
   */
  at?: number;
}

export type JsoncResult = { ok: true; value: unknown } | ({ ok: false } & JsoncFailure);

/**
 * Tolerant JSONC parse for the tsconfig family: strips line and block comments
 * plus trailing commas — outside string literals only — then `JSON.parse`. Vite
 * + TS starters ship tsconfigs *with comments* by default, so treating JSONC as
 * unreadable would false-red the doctor's alias check on the mainstream path.
 */
export function parseJsonc(text: string): JsoncResult {
  // Both passes accumulate into a STRING, not an array joined at the end. The
  // difference is that a string says when the scan reads past the end:
  // `'' + undefined` is the four characters "undefined", where
  // `[undefined].join('')` is silently empty. Every index bound in here was
  // therefore unfalsifiable — a scan running one character too far produced
  // byte-identical output — and the bounds are the whole correctness argument of
  // a hand-written scanner.
  let commentFree = '';

  for (let i = 0; i < text.length;) {
    if (text[i] === '"') {
      const literal = copyString(text, i);

      if (!literal.closed) {
        return { ok: false, reason: 'unterminated-string', at: literal.stoppedAt };
      }

      commentFree += literal.copied;
      i = literal.next;
    } else if (text[i] === '/' && text[i + 1] === '/') {
      // The comment ends at the newline, or at the end of a file that finishes in
      // one. `indexOf` answers with the position, so there is no bound to walk one
      // character past — the old `while (i < text.length && text[i] !== '\n')`
      // overran by one and nothing downstream could tell.
      const newline = text.indexOf('\n', i);

      i = newline === -1 ? text.length : newline;
    } else if (text[i] === '/' && text[i + 1] === '*') {
      // From AFTER the opener, or `/*/` reads as a closed comment: the `*/` the
      // search finds would be the opener's own `*` with the next `/`.
      const close = text.indexOf('*/', i + 2);

      if (close === -1) return { ok: false, reason: 'unclosed-comment', at: text.length };

      i = close + 2;
    } else {
      commentFree += text[i];
      i++;
    }
  }

  // Second pass, comment-free: drop a comma whose next non-space is `}`/`]`.
  let clean = '';

  for (let i = 0; i < commentFree.length;) {
    if (commentFree[i] === '"') {
      // Proven closed by the first pass, which copied this same literal. A cast
      // rather than a check: the check would be a branch no input can take, and an
      // unreachable branch is worse than a stated assumption — it reads as a case
      // somebody handled.
      const literal = copyString(commentFree, i) as ClosedString;

      clean += literal.copied;
      i = literal.next;
    } else if (commentFree[i] === ',') {
      // The next non-space AFTER the comma. Walking an index forward left the
      // walk's own bound undecidable: one past the end is `undefined`, which is
      // neither `}` nor `]`, so overrunning kept the comma exactly as stopping
      // would have.
      const after = /\S/.exec(commentFree.slice(i + 1));
      const nextChar = after?.[0];

      if (nextChar !== '}' && nextChar !== ']') clean += ',';

      i++;
    } else {
      clean += commentFree[i];
      i++;
    }
  }

  try {
    return { ok: true, value: JSON.parse(clean) };
  } catch {
    // Comments and trailing commas are gone, so what is left is a JSON mistake
    // rather than a JSONC one — a different thing to tell the reader. No offset:
    // JSON.parse's own position refers to the stripped text, not the file they
    // have open.
    return { ok: false, reason: 'not-json' };
  }
}

/** A tsconfig the JSONC reader gave up on, named so a caller can say which. */
export interface UnreadableConfig extends JsoncFailure {
  file: string;
}

const JSONC_REASON: Record<JsoncFailure['reason'], string> = {
  'unterminated-string': 'a string literal never closes',
  'unclosed-comment': 'a block comment never closes',
  'not-json': 'it is not valid JSON once the comments are stripped',
};

/**
 * The tsconfig/jsconfig files that are present but unparseable.
 *
 * Every reader of `paths` skips these, and skipping *silently* is the trap:
 * an alias declared inside an unreadable tsconfig is invisible, so doctor tells
 * an adopter to declare what is already there, and init calls a preset's alias
 * the repo's first. Both mislead in the same direction — they blame the alias for
 * a broken file. Callers name the file and the offset instead.
 */
export function unreadableTsconfigs(
  tsconfigs: Record<string, string | null>,
): UnreadableConfig[] {
  const failures: UnreadableConfig[] = [];

  for (const [file, text] of Object.entries(tsconfigs)) {
    if (text === null) continue;

    const result = parseJsonc(text);

    if (!result.ok) failures.push({ file, reason: result.reason, at: result.at });
  }

  return failures;
}

/**
 * One clause per unreadable config: which file, what is wrong, where to look.
 * Shared so doctor and init say it the same way — the same reason `quotedIn` is
 * the one wiredness standard both of them read.
 */
export function describeUnreadable(failures: UnreadableConfig[]): string {
  return failures
    .map(({ file, reason, at }) => {
      const where = at === undefined ? '' : ` at character ${at}`;

      return `${file} could not be read (${JSONC_REASON[reason]}${where})`;
    })
    .join('; ');
}

/** Visit every `compilerOptions.paths` entry across the given tsconfig texts. */
function eachPathAlias(
  tsconfigs: Record<string, string | null>,
  visit: (alias: string, dir: string | null) => void,
): void {
  for (const text of Object.values(tsconfigs)) {
    if (text == null) continue;

    const result = parseJsonc(text);

    // Undecidable: the `?.` below keeps this one honest. On a failure `result.value`
    // is `undefined`, the optional chain yields no options, and this file contributes
    // nothing either way — removing either alone still passes. The `?.` is separately
    // pinned by a tsconfig whose whole content is `null`, where it stops a throw.
    if (!result.ok) continue;

    const options = (result.value as { compilerOptions?: { paths?: unknown } })?.compilerOptions;
    const paths = options?.paths;

    if (typeof paths !== 'object' || paths === null) continue;

    for (const [key, targets] of Object.entries(paths)) {
      const alias = key.replace(/\/\*$/, '');

      if (!alias) continue;

      const target = Array.isArray(targets) && typeof targets[0] === 'string' ? targets[0] : null;

      visit(alias, target?.replace(/^\.\//, '').replace(/\/\*$/, '') ?? null);
    }
  }
}

/** Aliases in tsconfig/jsconfig `paths` that map onto `src/`, e.g. `@/* → ./src/*`. */
export function detectAliases(tsconfigs: Record<string, string | null>): Record<string, string> {
  const found: Record<string, string> = {};

  eachPathAlias(tsconfigs, (alias, dir) => {
    if (dir === 'src' && !(alias in found)) found[alias] = 'src';
  });

  return found;
}

/** Every alias declared in `paths`, whatever its target — "can TS resolve this prefix?". */
export function pathAliasKeys(tsconfigs: Record<string, string | null>): Set<string> {
  const keys = new Set<string>();

  eachPathAlias(tsconfigs, (alias) => keys.add(alias));

  return keys;
}

/**
 * Whether a JS config's text carries `name` as a quoted token (`'@': …`,
 * `find: '@'`, `.set('@', …)`). The shared wiredness standard for bundler
 * configs: doctor's alias check and init's alias instructs must agree, or
 * init nags about wiring doctor already accepts. A bare substring test would
 * be vacuous for short aliases — `'@'` is inside every `'@vitejs/plugin-…'`.
 */
export function quotedIn(text: string, name: string): boolean {
  return new RegExp(
    `['"\`]${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"\`]`,
  ).test(text);
}

/**
 * Whether `tsc -b` reads this repo's vite config — measured, not asserted.
 *
 * The playbook told an adopting agent to open its tsconfig and work this out,
 * and before that it asserted the answer ("A Vite + TS starter keeps
 * `vite.config.ts` inside a tsconfig project"). The assertion was false on the
 * shape this repo's own harness stages and came back as a finding three batches
 * running; the instruction that replaced it was correct and still put a
 * per-repo fact in prose, where it grew a conditional premise and then a third
 * unowned state. This is that fact with an address, the same move
 * `hadClaudeDir` was.
 *
 * `null` means "could not tell", and the playbook keeps its read-it-yourself
 * wording for that case only. Every bail-out below returns null rather than a
 * guess: a wrong verdict here is worse than no verdict, because the whole point
 * is that the report must not claim a build verified an edit it never read.
 */
/**
 * Local rather than shared: `bootstrap/alias.ts` has the same guard, and it sits
 * ABOVE this module in the layering — importing it here would run the one-way
 * rule backwards for a one-line predicate.
 */
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export interface ViteTsCoverage {
  /** `covered`: some project lists it. `outside`: projects exist, none does. */
  verdict: 'covered' | 'outside';
  /** The vite config, relative to root. */
  viteFile: string;
  /** The tsconfig that covers it, or the root one consulted when none does. */
  tsconfig: string;
}

export function viteTsCoverage(root: string): ViteTsCoverage | null {
  const viteFile = VITE_FILES.find((file) => fs.existsSync(path.join(root, file)));

  // No vite config, or a JS project with no tsconfig at all: there is no
  // question to answer, and the build clause has nothing to specialise.
  if (viteFile === undefined) return null;

  const rootConfig = 'tsconfig.json';
  const rootText = readText(path.join(root, rootConfig));

  if (rootText === null) return null;

  const projects = tsProjectGraph(root, rootConfig, rootText);

  if (projects === null) return null;

  for (const project of projects) {
    const covers = projectCovers(project, viteFile);

    // A single undecidable project poisons the whole answer: "none of them
    // covers it" cannot be claimed while one of them is unread.
    if (covers === null) return null;
    if (covers) return { verdict: 'covered', viteFile, tsconfig: project.file };
  }

  return { verdict: 'outside', viteFile, tsconfig: rootConfig };
}

export interface ClaudeDirState {
  /**
   * `.claude/` existed before this run, so it is the owner's whatever ends up in it.
   * Measured because the playbook used to assert init created it, which init knew and
   * had not checked — an agent went back to its own opening `ls -la` to be sure.
   */
  hadDir: boolean;
  /**
   * Command files in `.claude/commands/` other than the one init writes. The
   * cleanup sentence called that directory "now-empty" while measuring its parent,
   * so a repo with the owner's own commands beside blueprint's was told to delete a
   * directory that would not be empty (field run #139).
   */
  otherCommands: number;
}

/**
 * What `.claude/` looked like before this run — read before init writes anything,
 * because afterwards the tool cannot tell its own directory from the owner's.
 */
export function claudeDirState(root: string): ClaudeDirState {
  const dir = path.join(root, '.claude');
  const commands = path.join(dir, 'commands');
  const own = path.basename(COMMAND_FILE);

  return {
    hadDir: fs.existsSync(dir),
    otherCommands: readDir(commands).filter((entry) => entry !== own).length,
  };
}

/** Directory entries, or none when the directory is absent or unreadable. */
function readDir(dir: string): string[] {
  try {
    return fs.readdirSync(dir);
  } catch {
    return [];
  }
}

