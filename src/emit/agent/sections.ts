import type {
  ArchitectureDef,
  AxisDef,
  Blueprint,
  PlaybookSection,
  PrincipleDef,
  RuleSetting,
  Tier,
} from '../../config';
import {
  readSetting,
  getModuleShape,
  getSharedModule,
  normalizeAllowedImporters,
  sourcePath,
} from '../../config';
import { handbookPath } from '../docs';
import { enforcedBy, resolveTestFiles, unavailableForEmit } from '../lint';
import type { StackFacts } from '../lint';
import { formatOwns } from '../../markdown';

function rulesOfTier(rules: Record<string, RuleSetting> | undefined, tier: Tier) {
  return Object.entries(rules ?? {}).filter(([, setting]) => readSetting(setting).tier === tier);
}

function claudePrinciples(principles: PrincipleDef[] | undefined): PrincipleDef[] {
  if (!principles) {
    return [];
  }

  return principles.filter((principle) => principle.land === 'claude');
}

function gateLabel([id, setting]: [string, RuleSetting]): string {
  const value = readSetting(setting).value;

  return `\`${id}\`${value === undefined ? '' : ` = ${value}`}`;
}

function emittableGates(blueprint: Blueprint, stack: StackFacts): [string, RuleSetting][] {
  const { architecture, framework, rules } = blueprint;

  return rulesOfTier(rules, 'error').filter(
    ([id]) => unavailableForEmit(id, {
      framework,
      testFiles: architecture.testFiles,
      hasTypescript: stack.hasTypescript,
    }) === null,
  );
}

function inspectDiagnosisClause(gates: string): string {
  return `${gates} is diagnosed only when \`npx blueprint inspect --baseline\` runs; `
    + 'the baseline grandfathers recorded findings, so this is not continuous '
    + 'edit-time prevention and a green lint says nothing about it';
}

export function renderHeader(): string {
  return [
    '## Architecture contract (generated from blueprint)',
    '',
    '> Generated by `@kekkai/blueprint` — edit the blueprint, not this block.',
    '> Your own notes belong OUTSIDE the markers; init rewrites only between them.',
    '> The strictness is the product — it keeps AI development inside the declared',
    '> architecture. Never soften or bypass; disagreements go to the maintainer.',
  ].join('\n');
}

const CONTRACT_DOC = 'node_modules/@kekkai/blueprint/agent-contract.md';

export function renderCompactContract(blueprint: Blueprint, stack: StackFacts = {}): string {
  const { architecture } = blueprint;
  const chain = architecture.layers.map((layer) => `\`${layer.name}\``).join(' → ');
  const handbook = handbookPath(blueprint);

  const declared = emittableGates(blueprint, stack);
  const lintGates = declared.filter(([id]) => enforcedBy(id) === 'lint').map(gateLabel);
  const inspectGates = declared.filter(([id]) => enforcedBy(id) === 'inspect').map(gateLabel);

  const extras = [
    ...(blueprint.componentShape?.length ? ['component-shape axes'] : []),
    ...(claudePrinciples(blueprint.principles).length ? ['behavioral principles'] : []),
    ...(blueprint.playbook?.length ? ['the working playbook'] : []),
  ];

  return [
    renderHeader(),
    '',
    `- Framework: \`${blueprint.framework}\`. Import alias: \`${architecture.alias}\`.`,
    `- Layer flow: ${chain} — transitive: a layer may import **any** layer after it, unless the target narrows its importers.`,
    `- **Before adding, moving, or renaming any file** — placement, module shapes, ownership, naming${extras.length ? `, ${extras.join(', ')}` : ''}: read [${handbook}](${handbook}) (generated from the same blueprint — always current).`,
    '- **Operating discipline** — how to follow the flow, react to lint failures, '
    + `and the pre-commit checklist: read [${CONTRACT_DOC}](${CONTRACT_DOC}) `
    + '(ships inside the package — present once dependencies are installed, '
    + 'always matching the installed version).',

    `- Hard gates (machine-enforced on the files the layer globs match — a layer holding no code has nothing failing yet, which is runway, not protection): one-way imports, module entries, ownership, relative escapes${lintGates.length ? `, ${lintGates.join(', ')}` : ''} fail the project's lint run${inspectGates.length ? `; ${inspectDiagnosisClause(inspectGates.join(', '))}` : ''}. When lint fails, fix the structure — never \`eslint-disable\`, never relocate the violation to a sibling.`,

    `- You are the gate for: no undeclared folders under \`${architecture.alias}/\` (\`blueprint inspect --baseline\` verifies — red only on what you introduced). Its finding names two remedies and only one is yours: move the code into a module of an existing layer. If the architecture has genuinely outgrown this config, that is the owner's decision — say so and stop; never declare the layer yourself.`,
  ].join('\n');
}

export function renderContext(blueprint: Blueprint): string {
  const { framework, architecture } = blueprint;
  const chain = architecture.layers.map((layer) => `\`${layer.name}\``).join(' → ');

  return [
    '### Context',
    '',
    `- Framework: \`${framework}\`. Import alias: \`${architecture.alias}\`.`,
    `- Layer flow: ${chain}`,
  ].join('\n');
}

export function renderPlacement(architecture: ArchitectureDef): string {
  const lines = architecture.layers.map((layer) => {
    const parts = [`- \`${sourcePath(architecture, layer.name)}/\` — ${layer.does}.`];

    if (layer.mustNot?.length) {
      parts.push(` MUST NOT: ${layer.mustNot.join('; ')}.`);
    }

    const owns = formatOwns(layer.owns);

    if (owns) {
      parts.push(` OWNS: ${owns}.`);
    }

    if (layer.allowedImporters) {
      const importers = normalizeAllowedImporters(layer.allowedImporters)
        .map((importer) => (importer.selfOnly ? `${importer.layer} (selfOnly)` : importer.layer))
        .join(', ');

      parts.push(` IMPORTABLE BY: ${importers}.`);
    }

    return parts.join('');
  });

  const module = getSharedModule(architecture);
  const priv = module.private.map((part) => `\`${part}\``).join(' / ');

  const moduleLine
    = module.layout === 'folder'
      ? `- Module shape: one folder per module. Only \`${module.entry}\` is importable from outside${priv ? `; keep ${priv} private and never import them across modules` : ''}.`
      : '- Module shape: one file per module (flat). Extract shared logic to a lower layer.';

  const overrideLines = architecture.layers
    .filter((layer) => layer.module !== undefined)
    .map((layer) => {
      const shape = getModuleShape(architecture, layer.name);

      return shape.layout === 'folder'
        ? `- Exception — \`${sourcePath(architecture, layer.name)}/\`: one folder per module, entry \`${shape.entry}\`.`
        : `- Exception — \`${sourcePath(architecture, layer.name)}/\`: one file per module (flat).`;
    });

  const testGlobs = resolveTestFiles(architecture.testFiles);

  const exemptLine = testGlobs.length
    ? [`- Test support is exempt from every placement rule above as far as those globs reach: files matching ${testGlobs.map((glob) => `\`${glob}\``).join(' / ')} sit outside them, and a file none of them matches is placed by the rules above like any other. If a placement rule stops you on files that exist only to serve tests, that is a question for the owner — say so and name them; never widen \`architecture.testFiles\` yourself, and never rename a file to match those globs.`]
    : [];

  return [
    '### Where code goes',
    '',
    ...lines,
    moduleLine,
    ...overrideLines,
    ...exemptLine,
  ].join('\n');
}

export function renderNaming(naming: Record<string, string> | undefined): string {
  const entries = Object.entries(naming ?? {});

  if (!entries.length) {
    return '';
  }

  return [
    '### Naming',
    '',
    ...entries.map(([concept, convention]) => `- \`${concept}\`: ${convention}`),
  ].join('\n');
}

export function renderHardRules(blueprint: Blueprint, stack: StackFacts = {}): string {
  const { architecture } = blueprint;
  const bullets = ['- Import only from downstream layers — never upstream, never the same layer.'];

  const folderEntries = [
    ...new Set(
      architecture.layers
        .map((layer) => getModuleShape(architecture, layer.name))
        .filter((shape) => shape.layout === 'folder')
        .map((shape) => `\`${shape.entry}\``),
    ),
  ];

  if (folderEntries.length) {
    bullets.push(`- Import a module via its ${folderEntries.join(' / ')}, never its internals.`);
  }

  bullets.push(
    '- Restricted packages / globals live only in their owning layer (see "Where code goes").',
    '- Relative imports stay inside their module; no redundant segments (`./../`, `././`).',
  );

  for (const [id, setting] of emittableGates(blueprint, stack)) {
    const held = enforcedBy(id);
    const gate = gateLabel([id, setting]);

    if (held === 'lint') {
      bullets.push(`- ${gate} is a hard gate.`);
    }

    if (held === 'inspect') {
      bullets.push(`- ${inspectDiagnosisClause(gate)}.`);
    }
  }

  bullets.push(
    '- When lint fails, fix the structure — move the code or extract a lower layer. '
    + 'Never silence it with `eslint-disable`, and never relocate the violation to a sibling.',
  );

  return ['### Machine checks', '', ...bullets].join('\n');
}

export function renderComponentShape(axes: AxisDef[] | undefined): string {
  if (!axes?.length) {
    return '';
  }

  const bullets = axes.map((axis) => {
    const triage = axis.triage
      ? ` (triage: \`${axis.triage}\` is an entry point, never the verdict)`
      : '';

    return `- **${axis.name}** — ${axis.say} ${axis.why}${triage}`;
  });

  return [
    '### Component shape (orthogonal axes — judge each independently)',
    '',
    'A set, not a pipeline: never infer one axis holds because another does.',
    '',
    ...bullets,
  ].join('\n');
}

export function renderBehavioral(
  architecture: ArchitectureDef,
  principles: PrincipleDef[] | undefined,
  rules: Record<string, RuleSetting> | undefined,
): string {
  const bullets = [
    `- Do not create undeclared folders under \`${architecture.alias}/\`. Every folder is a declared layer or a module inside one. (lint can't see this — inspect will.) Inspect offers to declare the folder instead; that one is not yours. Outgrowing the config is the owner's call to make — report it, do not edit the architecture to fit what you just wrote.`,
    ...claudePrinciples(principles).map(
      (principle) => `- **${principle.say}** — ${principle.why}`,
    ),
  ];

  if (rules?.deadCode !== undefined && readSetting(rules.deadCode).tier === 'error') {
    bullets.push(
      '- **Dead code is error-tier, but no lint rule can gate it** — '
      + '`npx knip` is the gate (in init\'s install set); '
      + 'wire it into whatever verification you run.',
    );
  }

  if (rulesOfTier(rules, 'warn').length) {
    bullets.push(
      '- Treat a `warn`-tier lint result as a review entry point — look there, don\'t ignore it.',
    );
  }

  return [
    '### Behavioral rules (no tool enforces these — you are the gate)',
    '',
    ...bullets,
  ].join('\n');
}

export function renderPlaybook(playbook: PlaybookSection[] | undefined): string {
  if (!playbook?.length) {
    return '';
  }

  const blocks = playbook.map((section) =>
    [
      `#### ${section.title}`,
      '',
      ...section.rules.map(
        (rule) => `- **${rule.say}**${rule.why ? ` ${rule.why}` : ''}`,
      ),
    ].join('\n'));

  return [
    '### Working playbook (judgment rules — you are the gate)',
    '',
    ...blocks.join('\n\n').split('\n'),
  ].join('\n');
}

export function renderChecklist(blueprint: Blueprint): string {
  const { architecture, principles } = blueprint;

  const items = [
    '- [ ] Imports follow the one-way flow (no upstream / same-layer).',
    `- [ ] New code sits in the right layer; modules expose only \`${getSharedModule(architecture).entry}\`.`,
  ];

  if (architecture.naming && Object.keys(architecture.naming).length) {
    items.push('- [ ] Names follow the conventions above.');
  }

  items.push(`- [ ] No new undeclared folders under \`${architecture.alias}/\`.`);

  if (blueprint.componentShape?.length) {
    items.push('- [ ] Changed units hold against every component-shape axis, judged one by one.');
  }

  if (claudePrinciples(principles).length) {
    items.push('- [ ] The behavioral principles above are upheld.');
  }

  return ['### Before you commit', '', ...items].join('\n');
}
